#include <iostream>

int l[100005]; // l[i] 表示结点 i 的左儿子编号，0 表示不存在
int r[100005]; // r[i] 表示结点 i 的右儿子编号，0 表示不存在
int ans = 0;   // 满二叉树的计数

// DFS 函数：返回以 u 为根的子树的高度（若该子树是满二叉树），否则返回 -1
int dfs(int u) {
    // 情况 1：叶子结点（没有左儿子也没有右儿子）
    // 单个结点构成满二叉树，高度为 1
    if (l[u] == 0 && r[u] == 0) {
        ans++; // 计数 +1
        return 1;
    }

    // 情况 2：只有一个儿子（不是满二叉树，因为满二叉树要求非叶子结点必须有两个儿子）
    if (l[u] == 0 || r[u] == 0) {
        // 虽然当前子树不是满二叉树，但仍需递归处理存在的那个子树
        // 因为那个子树中可能包含满二叉树的子树
        if (l[u] != 0) dfs(l[u]);
        if (r[u] != 0) dfs(r[u]);
        return -1;
    }

    // 情况 3：有两个儿子，递归判断左右子树
    int hl = dfs(l[u]); // 左子树的高度（-1 表示不是满二叉树）
    int hr = dfs(r[u]); // 右子树的高度（-1 表示不是满二叉树）

    // 左右子树都是满二叉树且高度相同，则以 u 为根的子树也是满二叉树
    if (hl != -1 && hr != -1 && hl == hr) {
        ans++; // 计数 +1
        return hl + 1; // 整棵子树的高度 = 子树高度 + 1（当前结点这一层）
    }

    // 否则，以 u 为根的子树不是满二叉树
    return -1;
}

int main() {
    int n;
    std::cin >> n;

    // 读入每个结点的左右儿子编号
    for (int i = 1; i <= n; i++) {
        std::cin >> l[i] >> r[i];
    }

    // 从根结点（编号 1）开始 DFS
    dfs(1);

    // 输出满二叉树的数量
    std::cout << ans << std::endl;
    return 0;
}
