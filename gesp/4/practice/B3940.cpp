#include <iostream>

// 定义一个足够大的二维数组用于存放幻方阵
// 数组大小为25是为了确保能容纳最大的输入规模(21x21)
int array[25][25];

int main() {
    int n;
    std::cin >> n; // 输入幻方阵的阶数n（n为奇数）

    // 初始化：将1放在第一行的中间位置
    int mid = n / 2; // 计算中间列的位置
    array[0][mid] = 1; // 将1放在第一行的中间位置

    // 初始化填数相关变量
    int num = 2; // 下一个要填入的数字
    int l_n = 0, l_m = mid; // l_n, l_m分别表示上一个数字所在的行和列
    int c_n, c_m; // c_n, c_m用于计算下一个数字应该放置的位置（current_n和current_m的缩写）

    // 主循环：按照规则填充整个幻方阵
    while (num <= n * n) {
        // 第一步：尝试"上右"移动
        // 向上移动时的边界处理：第一行则转到最后一行
        c_n = l_n == 0 ? n - 1 : l_n - 1;
        // 向右移动时的边界处理：最后一列则转到第一列
        c_m = l_m == n - 1 ? 0 : l_m + 1;

        // 判断"上右"位置是否可用
        if (array[c_n][c_m] == 0) {
            // 如果"上右"位置为空，则填入当前数字
            array[c_n][c_m] = num; // 填入数字
            num++; // 准备填写下一个数字
            // 更新上一次填数的位置
            l_n = c_n;
            l_m = c_m;
        } else {
            // 如果"上右"位置已被占用，则尝试向下移动
            // 向下移动时的边界处理：最后一行则转到第一行
            c_n = l_n == n - 1 ? 0 : l_n + 1;
            c_m = l_m; // 列位置保持不变
            array[c_n][c_m] = num; // 填入数字，题目描述中说了该位置一定未占用，”神奇“。
            num++; // 准备填写下一个数字
            // 更新上一次填数的位置
            l_n = c_n;
            l_m = c_m;
        }
    }

    // 按格式要求输出幻方阵
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            std::cout << array[i][j] << " "; // 输出每个元素，空格分隔
        }
        std::cout << "\n"; // 每行结束换行
    }
    return 0;
}
